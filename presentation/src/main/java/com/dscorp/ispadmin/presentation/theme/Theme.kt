@Composable
fun MyTheme(
    darkTheme: Boolean = LocalThemeMode.current.isDark(isSystemInDarkTheme()),
    content: @Composable () -> Unit
) {
    val colorScheme = if (darkTheme) darkColorScheme else lightColorScheme
    val ispColors = if (darkTheme) DarkIspColors else LightIspColors
    CompositionLocalProvider(LocalIspColors provides ispColors) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = myTypography,
            content = content
        )
    }
}

/** Entry point for design-system values that MaterialTheme does not cover. */
object IspTheme {
    val colors: IspColors
        @Composable
        @ReadOnlyComposable
        get() = LocalIspColors.current
}
